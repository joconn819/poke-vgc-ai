"""Apply a learned scalar state-value model to Showdown search leaves."""

from __future__ import annotations

import math
import time
from typing import Any

import torch

from src.models.state_value import StateValueEvaluator
from src.env.public_battle_history import PublicBattleHistory
from src.training.data import build_model_inputs
from src.training.state_value import (
    STATE_VALUE_BASE_FIELD_DIM,
    STATE_VALUE_CONDITION_OBSERVATION_INDICES,
    _condition_age_history,
    _state_value_context,
)


def _mean_and_standard_error(values: list[float]) -> tuple[float, float | None]:
    if not values:
        raise ValueError("a chance-sample summary requires at least one value")
    mean = sum(values) / len(values)
    if len(values) < 2:
        return mean, None
    sample_variance = sum((value - mean) ** 2 for value in values) / (len(values) - 1)
    return mean, math.sqrt(sample_variance / len(values))


def _paired_difference_summary(
    selected_samples: dict[int, float], candidate_samples: dict[int, float]
) -> tuple[float, float | None]:
    shared_indices = sorted(set(selected_samples).intersection(candidate_samples))
    if not shared_indices:
        raise ValueError("paired action samples do not share chance seeds")
    return _mean_and_standard_error([
        selected_samples[index] - candidate_samples[index]
        for index in shared_indices
    ])


def _initialize_world_samples(
    reports: list[dict[str, Any]], candidate_count: int
) -> dict[int, list[list[dict[int, float]]]]:
    samples: dict[int, list[list[dict[int, float]]]] = {}
    for report in reports:
        world_index = int(report["world_index"])
        if world_index in samples:
            raise ValueError("duplicate learned frontier hidden-world index")
        response_count = int(report["opponent_response_count"])
        samples[world_index] = [
            [dict() for _ in range(response_count)]
            for _ in range(candidate_count)
        ]
    return samples


def _condition_age_key(observations: list[Any]) -> tuple[Any, ...]:
    """Key the small public condition-age encoder by its actual input bits."""
    indices = STATE_VALUE_CONDITION_OBSERVATION_INDICES
    maximum_index = max(indices)
    rows = []
    for observation in observations:
        if observation is None:
            rows.append(None)
            continue
        state = torch.as_tensor(observation, dtype=torch.float32).reshape(-1)
        if state.numel() <= maximum_index:
            rows.append(("short", int(state.numel())))
        else:
            rows.append(tuple(bool(state[index] > 0.5) for index in indices))
    return tuple(rows)


def apply_state_value_frontier(
    report: dict[str, Any],
    evaluator: StateValueEvaluator,
    probability_calibration: tuple[float, float] | None = None,
) -> tuple[dict[str, Any], float]:
    """Replace heuristic payoffs with learned acting-player win probabilities.

    ``frontier_states`` must be generated by the local Showdown search adapter
    from the acting player's own sets and a public species-only opponent view.
    The helper consumes the payload so private feature source material is not
    retained in logs or result summaries.
    """
    frontier_states = report.pop("frontier_states", [])
    if not frontier_states:
        raise ValueError("search did not return states for the learned value frontier")

    model = evaluator.state_model
    rows = []
    # Search leaves reuse the same acting-player sets and public six-species
    # preview. Cache their tokenized identity once, while build_model_inputs
    # still clones cached tensors so every row can safely add volatile fields.
    static_team_cache: dict[tuple[Any, ...], dict[str, torch.Tensor]] = {}
    condition_age_cache: dict[tuple[Any, ...], torch.Tensor] = {}
    for row in frontier_states:
        model_inputs = build_model_inputs(
            row["own_team"],
            row["opponent_team"],
            row["observation"],
            row.get("action_mask", [0] * 252),
            token_vocab_version=model.token_vocab_version,
            _static_team_cache=static_team_cache,
        )
        tracker = PublicBattleHistory()
        tracker.consume(row.get("public_history_lines", ()))
        public_mechanics = tracker.for_species_rosters(
            [str(member.get("species", "")) for member in row["own_team"]],
            [str(member.get("species", "")) for member in row["opponent_team"]],
            own_side="p1",
        )
        agent = "search_p1"
        prior_observation = row.get("previous_own_observation", [0.0] * 512)
        prior_actions = row.get("previous_own_action_indices", [0, 0])
        condition_observations = [prior_observation, row["observation"]]
        condition_key = _condition_age_key(condition_observations)
        prepared_condition_ages = condition_age_cache.get(condition_key)
        if prepared_condition_ages is None:
            prepared_condition_ages = _condition_age_history(condition_observations)
            condition_age_cache[condition_key] = prepared_condition_ages
        history = [
            {},
            {
                "observations": {agent: row["observation"]},
                "public_mechanics": {agent: public_mechanics},
            },
        ]
        history[0] = {
            "observations": {agent: prior_observation},
            "actions": {agent: prior_actions},
        }
        context = _state_value_context(
            history,
            1,
            agent,
            row.get("action_mask", [0] * 252),
            model_inputs,
            model.token_vocab_version,
            row["opponent_team"],
            str(row.get("format", report.get("format", ""))),
            prepared_condition_ages=prepared_condition_ages,
        )
        model_inputs["field_features"] = torch.cat(
            [model_inputs["field_features"][:STATE_VALUE_BASE_FIELD_DIM], context], dim=0
        )
        model_inputs.pop("action_mask", None)
        model_inputs.pop("opponent_move_indices", None)
        model_inputs.pop("opponent_item_indices", None)
        rows.append(model_inputs)
    excluded = {"action_mask", "opponent_move_indices", "opponent_item_indices"}
    batch = {
        key: torch.stack([row[key] for row in rows])
        for key in rows[0]
        if key not in excluded
    }
    device = next(evaluator.parameters()).device
    started = time.perf_counter()
    with torch.no_grad():
        values = evaluator(**{
            key: value.to(device) for key, value in batch.items()
        }).detach().cpu().reshape(-1).tolist()
    if probability_calibration is not None:
        slope, intercept = map(float, probability_calibration)
        if not math.isfinite(slope) or slope <= 0 or not math.isfinite(intercept):
            raise ValueError("frontier calibration requires a positive finite slope and finite intercept")
        epsilon = 1e-6

        def calibrate(value: float) -> float:
            clipped = max(epsilon, min(1.0 - epsilon, float(value)))
            logit = math.log(clipped) - math.log1p(-clipped)
            calibrated_logit = max(-35.0, min(35.0, slope * logit + intercept))
            return 1.0 / (1.0 + math.exp(-calibrated_logit))

        values = [calibrate(value) for value in values]
        report["frontier_probability_calibration"] = {
            "slope": slope,
            "intercept": intercept,
        }
    inference_ms = (time.perf_counter() - started) * 1000.0
    report["value_inference_device"] = str(device)

    reports = report["world_reports"]
    candidate_count = len(report["own_candidates"])
    samples_by_world = _initialize_world_samples(reports, candidate_count)
    for row, probability in zip(frontier_states, values, strict=True):
        world_index = int(row["world_index"])
        if world_index not in samples_by_world:
            raise ValueError("learned frontier refers to an unknown hidden-world index")
        action_index = int(row["row_index"])
        response_index = int(row["column_index"])
        sample_index = int(row.get("chance_sample_index", len(
            samples_by_world[world_index][action_index][response_index]
        )))
        cell_samples = samples_by_world[world_index][action_index][response_index]
        if sample_index in cell_samples:
            raise ValueError("duplicate learned frontier chance sample")
        cell_samples[sample_index] = float(probability)

    robust_scores = []
    for world_report in reports:
        world_samples = samples_by_world[int(world_report["world_index"])]
        payoff_matrix = []
        payoff_standard_error = []
        for action_samples in world_samples:
            payoff_row = []
            error_row = []
            for cell_samples in action_samples:
                indices = sorted(cell_samples)
                if not indices:
                    raise ValueError("missing learned frontier samples for an action pair")
                expected_count = int(world_report.get("chance_sample_count", len(indices)))
                if indices != list(range(expected_count)):
                    raise ValueError("learned frontier chance samples are incomplete or misindexed")
                mean, standard_error = _mean_and_standard_error(
                    [cell_samples[index] for index in indices]
                )
                payoff_row.append(mean)
                error_row.append(standard_error)
            payoff_matrix.append(payoff_row)
            payoff_standard_error.append(error_row)
        world_report["payoff_matrix"] = payoff_matrix
        world_report["payoff_standard_error"] = payoff_standard_error
        world_report["worst_response_by_own_action"] = [
            min(row) for row in payoff_matrix
        ]
    for action_index in range(candidate_count):
        robust_scores.append(min(
            world["worst_response_by_own_action"][action_index] for world in reports
        ))
    selected_index = max(range(len(robust_scores)), key=robust_scores.__getitem__)
    for world_report in reports:
        world_samples = samples_by_world[int(world_report["world_index"])]
        paired_rows = []
        for action_index, action_samples in enumerate(world_samples):
            delta_means = []
            delta_errors = []
            for response_index, selected_cell in enumerate(world_samples[selected_index]):
                action_cell = action_samples[response_index]
                mean, standard_error = _paired_difference_summary(
                    selected_cell, action_cell
                )
                delta_means.append(mean)
                delta_errors.append(standard_error)
            paired_rows.append({
                "action_index": action_index,
                "mean_selected_minus_action_by_response": delta_means,
                "standard_error_by_response": delta_errors,
            })
        world_report["paired_selected_action_differences"] = paired_rows
        world_report.pop("_sample_indices_by_cell", None)
    report["robust_scores"] = robust_scores
    report["selected_action_index"] = selected_index
    report["selected_action"] = report["own_candidates"][selected_index]
    report["frontier"] = "closed-sheet learned state-value probability"
    report["frontier_value"] = float(robust_scores[selected_index])
    return report, inference_ms
